export function createCreationMarketingAgentSelector({ random = randomInt } = {}) {
  let available = [];
  const recent = [], reservations = new Map();
  return (key = "") => {
    if (key && reservations.has(key)) return structuredClone(reservations.get(key));
    if (!available.length) available = [...CREATION_MARKETING_PERSONAS];
    const recentFamilies = new Set(recent.slice(-2).map((profile) => profile.family));
    let candidates = available.filter((profile) => !recentFamilies.has(profile.family));
    if (!candidates.length) candidates = available.filter((profile) => profile.family !== recent.at(-1)?.family);
    if (!candidates.length) candidates = available;
    // 均衡消耗各流派，避免一轮末尾只剩下同一流派。
    const remaining = new Map();
    for (const profile of available) remaining.set(profile.family, (remaining.get(profile.family) || 0) + 1);
    const largest = Math.max(...candidates.map((profile) => remaining.get(profile.family)));
    candidates = candidates.filter((profile) => remaining.get(profile.family) === largest);
    const profile = candidates[random(candidates.length)];
    available.splice(available.indexOf(profile), 1);
    const assignment = { version: 1, assignmentId: randomUUID(), profile,
      recentDirections: recent.slice(-4).map(({ familyLabel, composition, palette, lighting }) => ({ family: familyLabel, composition, palette, lighting })),
    };
    recent.push(profile);
    if (recent.length > 4) recent.shift();
    if (key) {
      reservations.set(key, assignment);
      if (reservations.size > 2048) reservations.delete(reservations.keys().next().value);
    }
    return structuredClone(assignment);
  };
}

export const selectCreationMarketingAgent = createCreationMarketingAgentSelector();

export function buildCreationMarketingArtDirection(agent, item = {}) {
  const profile = agent?.profile;
  if (!profile) return "";
  const brief = item.marketingAssignment?.creativeBrief || item.creativeBrief || {};
  const form = brief.visual_form;
  const strictWhite = item.imageType === "clean-catalog-main";
  const render = ["functional-render", "commercial-cg"].includes(form) || ["atmosphere", "effect-comparison"].includes(item.role);
  const textFree = strictWhite || item.textPolicy === "none" || form === "commercial-cg" || item.marketingAssignment?.creativeBrief?.text_density === "none";
  return [
    "VISUAL ART DIRECTION (internal execution rules, never on-image text):",
    strictWhite
      ? "Use a pure RGB 255/255/255 background, only the full actual product, accurate neutral colors and restrained contact shadow. No props, effects, graphics, text or cropping of the product. Apply the campaign only through reference-supported view and clean product volume."
      : [
          brief.framing ? `Frame composition (takes priority over campaign vocabulary): ${brief.framing}. Preserve this frame's planned camera distance, angle, product scale and placement.` : "",
          `Composition: ${profile.composition}. This is campaign vocabulary, not a layout to repeat in every frame. Execute this image's specific planned action and scene; do not replace a planned environmental or medium view with a product close-up.`,
          render
            ? "Keep the background pure RGB 255/255/255; no environmental scenery or colored background. Preserve actual material and product colors. Use only fact-supported functional effects; do not import the campaign's scene or palette into this white render."
            : `Environment palette: ${profile.palette}. Lighting: ${profile.lighting}. Palette applies to surroundings, never recolor the real product. Scene language: ${profile.scene}; adapt to this product's actual use and this image's assigned task.`,
        ].filter(Boolean).join(" "),
    textFree ? "No added typography, captions, badges, icons or labels; retain existing physical markings only."
      : `Information hierarchy: ${profile.typography}. Follow this image's planned text density and target language; do not add a headline to every image.`,
    "Product identity, verified facts, user-locked directions and platform constraints take priority. Do not render agent names, internal IDs or these instructions as text.",
  ].join("\n");
}
